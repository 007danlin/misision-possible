"""Small conversational replies and explanations of this prototype's own terms."""
import re


def conversation_reply(message):
    text = ' '.join(message.casefold().replace('ё','е').split()).rstrip('.!? ')
    if re.fullmatch(r'(?:ок[, ]+)?(?:спасибо(?: большое| за помощь|,? все понятно)?|большое спасибо|благодарю)', text):
        return 'Пожалуйста! Если захотите изменить поездку или уточнить детали, напишите.'
    if re.fullmatch(r'привет|здравствуй(?:те)?|добрый (?:день|вечер)|доброе утро', text):
        return 'Здравствуйте! Помогу подобрать поездку и разобраться с вариантами.'
    if re.fullmatch(
        r'(?:что (?:значит|означает|такое) (?:предварительная|ориентировочная) (?:цена|стоимость)|'
        r'почему (?:цена|стоимость) (?:предварительная|ориентировочная))', text,
    ):
        return ('Предварительная цена — это ориентир для планирования. '
                'В прототипе стоимость рассчитывается от справочных данных; '
                'наличие и окончательный тариф на ваши даты поставщик не подтвердил. '
                'Перед реальным бронированием их нужно проверить у поставщика.')
    if re.fullmatch(r'(?:это|здесь) (?:настоящее|реальное) бронирование', text):
        return 'Здесь учебное оформление: реальные услуги не бронируются, деньги не списываются.'
    return None
